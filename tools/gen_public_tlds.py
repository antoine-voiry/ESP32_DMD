#!/usr/bin/env python3
"""Writes src/core/PublicTlds.h from IANA's list of top-level domains.

The web pages' DNS-rebinding guard (src/core/WebGuard.cpp) refuses a user-set LAN domain that is a
public top-level domain. Two-letter labels (country codes) are refused by a rule, so only longer
ones are listed. Rerun now and then to pick up new TLDs:

    curl -o /tmp/tlds.txt https://data.iana.org/TLD/tlds-alpha-by-domain.txt
    python3 tools/gen_public_tlds.py /tmp/tlds.txt
"""

import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "core" / "PublicTlds.h"


def main(path: str) -> None:
    lines = pathlib.Path(path).read_text().splitlines()
    version = lines[0].lstrip("# ").strip()
    names = sorted({l.strip().lower() for l in lines[1:] if l.strip() and not l.startswith("#")})
    names = [n for n in names if len(n) > 2]
    rows, row = [], "|"
    for n in names:
        if len(row) + len(n) + 1 > 100:
            rows.append(row)
            row = ""
        row += n + "|"
    rows.append(row)
    body = "\n".join(f'    "{r}"' for r in rows)
    text = f"""#ifndef DMD_CORE_PUBLIC_TLDS_H
#define DMD_CORE_PUBLIC_TLDS_H

// Generated by tools/gen_public_tlds.py from IANA's list ({version}).
// Every public top-level domain longer than two letters, lower-case, as "|name|name|...|".

namespace dmd {{

constexpr const char* kPublicTlds =
{body};

}}  // namespace dmd

#endif
"""
    # C++ sources keep CRLF line endings in this repository (.editorconfig).
    OUT.write_bytes(text.replace("\n", "\r\n").encode())
    print(f"{OUT}: {len(names)} TLDs")


if __name__ == "__main__":
    main(sys.argv[1])
